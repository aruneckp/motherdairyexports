export function ruleFor(country: Country, category: CategoryId): { level: RuleLevel; note: string } {
  const rule = country.rules.find((r) => r.categories.includes(category))
  if (rule) return { level: rule.level, note: rule.note }
  return { level: 'ok', note: 'No product-specific restriction on record. Standard documentation applies.' }
}
